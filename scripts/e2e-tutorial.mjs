import { chromium } from "playwright";
// 手引き(チュートリアル)を画面で最後まで進める確認。先に pnpm dev で起動しておく。使い方: node scripts/e2e-tutorial.mjs [スクリーンショットの出力先]
import { mkdirSync, readFileSync } from "node:fs";
const sc = JSON.parse(readFileSync("data/scenarios/bastogne-1944-12-19.json", "utf8"));
const widthM = sc.map.rows[0].length * sc.map.cellSizeM, heightM = sc.map.rows.length * sc.map.cellSizeM;
const out = process.argv[2] ?? "test-results";
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" }).catch(() => chromium.launch());
const page = await browser.newPage({ viewport: { width: 1400, height: 860 } });
const logs = [];
page.on("pageerror", (e) => logs.push(`pageerror: ${e.message}`));
page.on("console", (m) => m.type() === "error" && logs.push(m.text()));
await page.goto("http://localhost:5173/");
await page.getByTestId("tutorial-bastogne-basics").click();
await page.getByTestId("end-turn").waitFor({ timeout: 15000 });
const title = async () => (await page.locator(".tutorial h4").innerText());
const shot = async (n) => page.screenshot({ path: `${out}/tut-${n}.png` });
console.log(1, await title()); await shot(1);
await page.getByTestId("tutorial-next").click();
console.log(2, await title());
await page.getByTestId("tutorial-next").click();
console.log(3, await title()); await shot(3);
await page.getByTestId("unit-us-501-pir").click();
console.log(4, await title()); await shot(4);
await page.getByTestId("tutorial-next").click();
console.log(5, await title()); await shot(5);
// ビゾリーの印を押す(地図の座標から画面の位置を計算する)
const box = await page.getByTestId("map").boundingBox();
// 地図は開いたとき全体が収まる表示(fitCamera と同じ計算)
const toScreen = (p) => { const k = Math.min(box.width / widthM, box.height / heightM) * 0.95; return { x: box.width / 2 + (p.x - widthM / 2) * k, y: box.height / 2 - (p.y - heightM / 2) * k }; };
const pos = toScreen({ x: 18125, y: 14375 });
await page.mouse.click(box.x + pos.x, box.y + pos.y);
await page.waitForTimeout(500);
console.log(6, await title()); await shot(6);
await page.getByTestId("tutorial-next").click();
console.log(7, await title());
await page.getByTestId("deploy-after-stop").locator("input").check();
console.log(8, await title());
await page.getByTestId("tutorial-next").click();
console.log(9, await title());
await page.getByTestId("unit-us-team-cherry").click();
console.log(10, await title()); await shot(10);
await page.getByTestId("fire-mission-us-101-divarty").click();
const pos2 = toScreen({ x: 19625, y: 13625 });
await page.mouse.click(box.x + pos2.x, box.y + pos2.y);
await page.waitForTimeout(300);
console.log(11, await title());
await page.getByTestId("tutorial-next").click();
console.log(12, await title()); await shot(12);
await page.getByTestId("end-turn").click();
await page.getByText("再生を飛ばす").click({ timeout: 20000 });
await page.getByTestId("end-turn").waitFor({ timeout: 20000 });
await page.waitForTimeout(500);
console.log(13, await title()); await shot(13);
await page.getByTestId("tutorial-next").click();
console.log(14, await title()); await shot(14);
const last = await title();
console.log("browser errors:", logs.join("\n") || "(none)");
if (last !== "勝つための要点" || logs.length) process.exitCode = 1;
await browser.close();
